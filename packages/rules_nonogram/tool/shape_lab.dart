void main() {
  var pass = 0;
  for (final shape in candidates) {
    final n = shape.size;
    print('--- ${shape.id} (${n}x$n) ---');
    var wellFormed = shape.rows.length == n;
    for (var r = 0; r < shape.rows.length; r++) {
      if (shape.rows[r].length != n) {
        print('  row $r is ${shape.rows[r].length} wide: "${shape.rows[r]}"');
        wellFormed = false;
      }
    }
    if (!wellFormed) {
      print('  MALFORMED — fix widths first\n');
      continue;
    }

    final grid = shape.toGrid();
    final density = shape.density;

    bool rowUsed(int r) =>
        List.generate(n, (c) => grid[r * n + c]).any((v) => v == Cell.filled);
    bool colUsed(int c) =>
        List.generate(n, (r) => grid[r * n + c]).any((v) => v == Cell.filled);
    final edges = [rowUsed(0), rowUsed(n - 1), colUsed(0), colUsed(n - 1)]
        .where((e) => e)
        .length;

    final clues = NonogramSolver.cluesFor(grid, width: n, height: n);
    final result =
        NonogramSolver(rowClues: clues.rows, colClues: clues.cols).solve();

    final densityOk = density > 0.2 && density < 0.85;
    final matches = result.solved &&
        List.generate(grid.length, (i) => i).every(
            (i) => (grid[i] == Cell.filled) == (result.board[i] == Cell.filled));

    final ok = densityOk && edges >= 3 && matches;
    if (ok) pass++;
    print('  ${ok ? "PASS" : "FAIL"}: density ${(density * 100).toStringAsFixed(0)}% '
        '${densityOk ? "ok" : "FAIL"} | edges $edges/4 '
        '${edges >= 3 ? "ok" : "FAIL"} | '
        'solved ${result.solved} (hardest ${result.hardest.name}, '
        '${result.passes} passes) | picture match $matches');

    if (!result.solved) {
      final undecided = result.board.where((v) => v == Cell.unknown).length;
      print('  stalls with $undecided undecided cells:');
      for (var r = 0; r < n; r++) {
        final line = StringBuffer('    ');
        for (var c = 0; c < n; c++) {
          final v = result.board[r * n + c];
          line.write(v == Cell.unknown ? '?' : (v == Cell.filled ? '#' : '.'));
        }
        print(line);
      }
    }
    print('');
  }
  print('$pass/${candidates.length} pass');
}
